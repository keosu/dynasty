// Curated facts override imported summaries, while source excerpts stay available.
const merged: Emperor[] = [];
const matched = new Set<string>();
for (const raw of importedRecords) {
  const imported = raw as Emperor;
  const curated = curatedEmperors.find(
    (p) =>
      p.dynastyId === imported.dynastyId &&
      (p.name === imported.name ||
        p.name === imported.sourceTitle ||
        p.title === imported.sourceTitle ||
        p.sources.some(
          (s) => decodeURIComponent(s.url.split('/wiki/')[1] || '') === imported.sourceTitle,
        )),
  );
  if (curated) {
    if (matched.has(curated.id)) continue;
    matched.add(curated.id);
    merged.push({
      ...imported,
      ...curated,
      articleSections: imported.articleSections,
      parentNames: imported.parentNames,
      reignText: imported.reignText,
      eraNames: imported.eraNames,
      imported: false,
      sources: [
        ...curated.sources,
        ...imported.sources.filter((s) => !curated.sources.some((c) => c.url === s.url)),
      ],
    });
  } else {
    merged.push({
      ...imported,
      summary:
        imported.summary ||
        '在位时间与身份已从公开君主表收录；人物正文暂未成功提取，可通过下方来源阅读原文。',
      claimant: ['李重福', '李承宏', '李煴', '李熅', '李缊', '李蕴'].includes(imported.name),
    });
  }
}
export const emperors: Emperor[] = [
  ...merged,
  ...curatedEmperors.filter((p) => !matched.has(p.id)),
];
